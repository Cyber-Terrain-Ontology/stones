#!/usr/bin/env bash
# Build ontologies/stones-merged.ttl: STONES as one file, for loading into a
# triplestore or generating documentation (WIDOCO).
#
# The repo keeps STONES split into modules (stones.ttl imports the property and
# vocabulary files). The merge is their union, minus the modules' own
# owl:Ontology headers and stones.ttl's owl:imports of them, so it has a single
# header: stones.ttl's, with its version.
#
# Needs Apache Jena (sparql; set JENA_HOME or put its bin on PATH) and the EDM
# Council rdf-toolkit jar (RDF_TOOLKIT; the stonework repo's tools/download-rdf-toolkit.sh
# fetches it), which sorts the output so a rebuild only diffs where STONES changed.
#
# Usage: bash tools/build-merged.sh [OUTPUT]   (default ontologies/stones-merged.ttl)
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
ONT="$ROOT/ontologies"
OUT="${1:-$ONT/stones-merged.ttl}"
MODULES="stones.ttl datatype-properties.ttl object-properties.ttl vocabularies.ttl"

if [ -n "${JENA_HOME:-}" ] && [ -x "$JENA_HOME/bin/sparql" ]; then SPARQL="$JENA_HOME/bin/sparql"
elif command -v sparql >/dev/null; then SPARQL=sparql
elif [ -n "${JENA_HOME:-}" ] && [ -f "$JENA_HOME/bat/sparql.bat" ]; then SPARQL="$JENA_HOME/bat/sparql.bat"
else echo "ERROR: Apache Jena not found (set JENA_HOME)" >&2; exit 1; fi

JAR="${RDF_TOOLKIT:-$ROOT/../stonework/tools/rdf-toolkit.jar}"
[ -f "$JAR" ] || { echo "ERROR: rdf-toolkit.jar not found (set RDF_TOOLKIT)" >&2; exit 1; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
cat > "$TMP/merge.rq" <<'RQ'
PREFIX owl: <http://www.w3.org/2002/07/owl#>
CONSTRUCT { ?s ?p ?o } WHERE {
  ?s ?p ?o
  # the modules' own headers ...
  FILTER NOT EXISTS {
    ?s a owl:Ontology
    FILTER(?s IN (<https://cyberterrain.org/ns/datatype-properties#>,
                  <https://cyberterrain.org/ns/object-properties#>,
                  <https://cyberterrain.org/ns/vocabularies#>))
  }
  # ... and the imports of them; other imports (SKOS) stay
  FILTER(!(?p = owl:imports && ?o IN (<https://cyberterrain.org/ns/datatype-properties#>,
                                      <https://cyberterrain.org/ns/object-properties#>,
                                      <https://cyberterrain.org/ns/vocabularies#>)))
}
RQ
cd "$ONT"
args=(); for m in $MODULES; do args+=(--data "$m"); done
"$SPARQL" "${args[@]}" --query "$TMP/merge.rq" --results=TTL > "$TMP/merged.ttl"
java -jar "$JAR" -sfmt turtle -tfmt turtle --inline-blank-nodes -s "$TMP/merged.ttl" -t "$TMP/canon.ttl"
python3 - "$TMP/canon.ttl" "$OUT" <<'PY'
import sys
from pathlib import Path
text = Path(sys.argv[1]).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n"
header = ("# STONES — STIX ONtology Expression System, as a single file.\n"
          "# GENERATED by tools/build-merged.sh from ontologies/stones.ttl, datatype-properties.ttl,\n"
          "# object-properties.ttl and vocabularies.ttl. Edit those, not this file.\n\n")
Path(sys.argv[2]).write_text(header + text, encoding="utf-8", newline="\n")
PY

# Sanity checks: fail loudly rather than ship a broken merge.
n_ont=$(grep -c "owl:Ontology" "$OUT" || true)
[ "$n_ont" -eq 1 ] || { echo "FAIL: expected 1 owl:Ontology, found $n_ont" >&2; exit 1; }
grep -q 'owl:versionInfo' "$OUT" || { echo "FAIL: no owl:versionInfo" >&2; exit 1; }
for term in stones:ThreatActor stones:created stones:createdByRef; do
  grep -qE "^$term\b|^<https://cyberterrain.org/ns/stones#${term#stones:}>" "$OUT" || { echo "FAIL: $term missing" >&2; exit 1; }
done
echo "wrote $OUT"
